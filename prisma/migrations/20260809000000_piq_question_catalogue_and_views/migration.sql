    "position" INTEGER NOT NULL,

    CONSTRAINT "PIQQuestion_pkey" PRIMARY KEY ("id")
);

CREATE INDEX IF NOT EXISTS "PIQQuestion_section_position_idx" ON "PIQQuestion"("section", "position");

