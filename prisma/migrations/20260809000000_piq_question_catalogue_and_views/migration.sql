-- Readable supplier data for Beekeeper / Metabase / plain SQL.
--
-- The answers suppliers actually fill in live in JSONB keyed by field id:
-- ProductPIQ.answers, SupplierProfile.eoiAnswers and .stageAnswers. A database
-- client shows those as one opaque JSON cell per row, so you cannot sort by
-- shelf life, find products missing an HS code, or compare answers across
-- suppliers without hand-writing `answers->>'...'` every time — and the field
-- ids themselves are only documented in TypeScript.
--
-- This migration adds:
--   * "PIQQuestion"     — the question catalogue, mirrored from piq-config.ts
--   * "v_piq_answer"    — one row per answered PIQ question, labelled
--   * "v_supplier_answer" — the same for the EOI + journey stage forms
--
-- Long format (a row per answer) rather than one column per question: it
-- survives questions being added or removed, which a wide view does not.
--
-- Idempotent throughout, for the same reason as
-- 20260808000000_supplier_portal_cms_service_tokens: railway.toml runs
-- `prisma migrate deploy && node dist/server.js`, so any error here stops the
-- API from booting.

-- ---------------------------------------------------------------- catalogue

