-- One row per answered PIQ question, with the question text resolved.
-- Unanswered questions do not appear; use "PIQQuestion" LEFT JOINed to this
-- view when you want the gaps instead.
CREATE OR REPLACE VIEW "v_piq_answer" AS
SELECT
    s."companyName"                                  AS company,
    p.name                                           AS product,
    p.status::text                                   AS piq_status,
    p.completion,
    q."sectionTitle"                                 AS section,
    COALESCE(q.label, a.key)                         AS question,
    CASE jsonb_typeof(a.value)
        WHEN 'string' THEN NULLIF(a.value #>> '{}', '')
        WHEN 'null'   THEN NULL
        WHEN 'array'  THEN NULLIF(
            (SELECT string_agg(e #>> '{}', ' | ') FROM jsonb_array_elements(a.value) e), '')
        ELSE a.value::text
    END                                              AS answer,
    q.required,
    a.key                                            AS question_id,
    q."position"                                     AS question_position,
    p."updatedAt"                                    AS updated_at,
    p.id                                             AS piq_id,
    s.id                                             AS supplier_id
FROM "ProductPIQ" p
JOIN "SupplierProfile" s ON s.id = p."supplierId"
-- CASE guard: jsonb_each() errors on a non-object, so a malformed row would
-- otherwise take out the whole view rather than just itself.
CROSS JOIN LATERAL jsonb_each(
    CASE WHEN jsonb_typeof(p.answers) = 'object' THEN p.answers ELSE '{}'::jsonb END
) AS a(key, value)
LEFT JOIN "PIQQuestion" q ON q.id = a.key;

-- The EOI form and the journey stage forms. stageAnswers is nested one level
-- deeper ({ stage: { field: value } }) than eoiAnswers ({ field: value }), so
-- the two are flattened separately and unioned.
CREATE OR REPLACE VIEW "v_supplier_answer" AS
SELECT
    s."companyName"                                  AS company,
    'Stage ' || st.key                               AS form,
    f.key                                            AS question_id,
    CASE jsonb_typeof(f.value)
        WHEN 'string' THEN NULLIF(f.value #>> '{}', '')
        WHEN 'null'   THEN NULL
        WHEN 'array'  THEN NULLIF(
            (SELECT string_agg(e #>> '{}', ' | ') FROM jsonb_array_elements(f.value) e), '')
        ELSE f.value::text
    END                                              AS answer,
    s."currentStage"                                 AS current_stage,
    s.status::text                                   AS supplier_status,
    s."updatedAt"                                    AS updated_at,
    s.id                                             AS supplier_id
FROM "SupplierProfile" s
CROSS JOIN LATERAL jsonb_each(
    CASE WHEN jsonb_typeof(s."stageAnswers") = 'object' THEN s."stageAnswers" ELSE '{}'::jsonb END
) AS st(key, value)
CROSS JOIN LATERAL jsonb_each(
    CASE WHEN jsonb_typeof(st.value) = 'object' THEN st.value ELSE '{}'::jsonb END
) AS f(key, value)

UNION ALL

SELECT
    s."companyName",
    'EOI',
    f.key,
    CASE jsonb_typeof(f.value)
        WHEN 'string' THEN NULLIF(f.value #>> '{}', '')
        WHEN 'null'   THEN NULL
        WHEN 'array'  THEN NULLIF(
            (SELECT string_agg(e #>> '{}', ' | ') FROM jsonb_array_elements(f.value) e), '')
        ELSE f.value::text
    END,
    s."currentStage",
    s.status::text,
    s."updatedAt",
    s.id
FROM "SupplierProfile" s
CROSS JOIN LATERAL jsonb_each(
    CASE WHEN jsonb_typeof(s."eoiAnswers") = 'object' THEN s."eoiAnswers" ELSE '{}'::jsonb END
) AS f(key, value);

